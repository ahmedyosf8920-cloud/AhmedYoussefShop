begin
 if (select count(*) from public.store_reviews where created_at > now() - interval '10 minutes') >= 20 then
  raise exception 'too many reviews, try again later';
 end if;
 return new;
end $$;
drop trigger if exists store_reviews_guard_trg on public.store_reviews;
create trigger store_reviews_guard_trg before insert on public.store_reviews for each row execute function public.store_reviews_guard();

