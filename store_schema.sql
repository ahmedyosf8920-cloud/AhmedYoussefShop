-- 2) حماية من الإزعاج (spam): حد أقصى للطلبات والتقييمات في الفترة القصيرة
create or replace function public.store_orders_guard() returns trigger
language plpgsql security definer set search_path = public as $$
begin
 if (select count(*) from public.store_orders where created_at > now() - interval '10 minutes') >= 40 then
  raise exception 'too many orders, try again later';
 end if;
 if (select count(*) from public.store_orders where phone = new.phone and created_at > now() - interval '1 hour') >= 5 then
  raise exception 'too many orders from this phone, try again later';
 end if;
 return new;
end $$;
drop trigger if exists store_orders_guard_trg on public.store_orders;
create trigger store_orders_guard_trg before insert on public.store_orders for each row execute function public.store_orders_guard();

create or replace function public.store_reviews_guard() returns trigger
