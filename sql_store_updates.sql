drop policy if exists "Visitors log a visit" on public.store_visits;
create policy "Visitors log a visit" on public.store_visits for insert to anon, authenticated with check (true);
drop policy if exists "Owner reads visits" on public.store_visits;
create policy "Owner reads visits" on public.store_visits for select to authenticated using ((auth.jwt() ->> 'email') = 'ahmedyosf8910@gmail.com');
grant insert on public.store_visits to anon, authenticated;
grant select on public.store_visits to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

